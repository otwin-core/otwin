def test_a_too_short_record_is_refused_with_a_clear_message():
    with pytest.raises(NotEnoughData) as err:
        HourlyData(START, np.full(240, 0.4), np.full(240, 8.0))
    msg = str(err.value)
    assert "at least 28 days" in msg and "covers 10 days" in msg
    assert "Datadis" in msg  # says what to do about it


def test_one_hour_short_is_still_too_short():
    n = 28 * 24 - 1
    with pytest.raises(NotEnoughData, match="27 days and 23 hours"):
        HourlyData(START, np.full(n, 0.4), np.full(n, 8.0))
    HourlyData(START, np.full(n + 1, 0.4), np.full(n + 1, 8.0))  # four weeks: accepted


def test_missing_hours_are_tolerated_up_to_ten_percent():
    n = 31 * 24
    e = np.full(n, 0.5)
    e[100:137] = np.nan  # 5 %
    assert HourlyData(START, e, np.full(n, 8.0)).observed.sum() == n - 37
    e[200:300] = np.nan  # now 18 %
    with pytest.raises(NotEnoughData, match=r"137 of the 744 hours.*05/01/2026 04:00"):
        HourlyData(START, e, np.full(n, 8.0))


def test_the_weather_must_cover_the_record():
    n = 31 * 24
    o = np.full(n, 8.0)
    o[50:60] = np.nan
    with pytest.raises(
        NotEnoughData, match="outdoor temperature is missing for 10 hours"
    ):
        HourlyData(START, np.full(n, 0.5), o)
    with pytest.raises(ValueError, match="kelvin"):
        HourlyData(START, np.full(n, 0.5), np.full(n, 281.15))


