"""Calibration: recover known homes from synthetic months, and say when it cannot.

Every month here is generated by :func:`calibration.synthetic_month` from a
home whose parameters are known, on a 5-minute grid with two months of
weather history before the record, so the calibration sees data from a state
it does not know, exactly as with a real meter. The fit then starts from
deliberately wrong values (50 % off) and must find the truth:

* noise-free, to within 1 %;
* with a real household's noise (5 % per hour plus 0.08 kWh of appliance use
  the twin does not know about), to within what it reports as its own
  uncertainty;

and it must say "not enough data", with the reason, when the month cannot
answer: a heater that never ran at full power, a house kept at one
temperature, heating on gas, or a twin missing a big load. A record shorter
than four weeks is refused before any fitting.

Fits run on the fastest backend installed: the Rust engine when present
(the CI engine job), NumPy otherwise; parity between them is tested in
test_components_*.py.
"""

