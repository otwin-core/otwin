@pytest.fixture(scope="module")
def clean():
    data = month(flat(), noisy=False)
    return data, calibrate(flat(), data, guess=WRONG)


@pytest.fixture(scope="module")
def noisy():
    data = month(flat(), noisy=True)
    return data, calibrate(flat(), data, guess=WRONG)


def test_noise_free_month_recovers_every_parameter(clean):
    data, res = clean
    for name, err in errors(res).items():
        assert abs(err) < 0.01, f"{name} off by {100 * err:.2f} %"
    assert res.verdict == GOOD
    assert all(f.verdict == GOOD for f in res.findings)
    assert (
        res.hourly_error < 0.03
    )  # what is left is the 5-minute truth vs a 15-minute fit


def test_noisy_month_recovers_within_its_own_uncertainty(noisy):
    """The reported ± must cover the truth. Tolerances from the task:
    heat loss and heater size ±5 %, heat storage ±10 %, base load ±15 %."""
    data, res = noisy
    err = errors(res)
    assert abs(err["zone.envelope.conductance"]) < 0.05
    assert abs(err["zone.air.capacity"]) < 0.10
    assert abs(err["heating.thermostat.power"]) < 0.05
    assert abs(err["base.power"]) < 0.15
    for name, e in err.items():
        assert abs(e) <= 1.5 * res.uncertainty[name], (name, e, res.uncertainty[name])
    assert res.verdict in (GOOD, USABLE)
    # a real household's noise shows: about 10 % per hour, nothing on the month
    assert 0.05 < res.hourly_error < 0.15
    assert abs(res.bias) < 0.01


def test_the_report_reads_as_plain_language(noisy):
    _, res = noisy
    text = res.summary()
    assert text.startswith("Calibration: GOOD") or text.startswith("Calibration: USABLE")
    assert "How fast your home loses heat:" in text
    assert "W for every °C" in text and "kW" in text and "hours" in text
    assert "Size of your heat pump" in text and "Always-on electricity" in text
    for f in res.findings:
        assert f.verdict in (GOOD, USABLE, NOT_ENOUGH_DATA)
        assert f.measured and f.uncertainty is not None
    # the time constant is C / (UA + ventilation): about 16 hours here
    tau = res.finding("zone.air.capacity")
    assert tau.unit == "hours" and tau.value == pytest.approx(1.2e7 / 210 / 3600, rel=0.1)


def test_the_calibrated_twin_reproduces_the_month(noisy):
    data, res = noisy
    again = HourlyMeter(res.twin, data).simulate(data.t)["electricity"]
    obs = data.observed
    np.testing.assert_allclose(again[obs], res.predicted_kwh[obs], rtol=1e-10)
    assert res.twin.model.parameters["base.power"] == res.values["base.power"]
    assert np.nansum(res.predicted_kwh) == pytest.approx(
        np.nansum(res.measured_kwh), rel=0.01
    )


# ---------------------------------------------------------------- what a month cannot show


def test_a_heater_that_never_ran_at_full_power_is_not_sized():
    """12 kW for a flat that needs 3, a steady 20 °C, a mild month: the heater's
    size and the home's heat storage never show; its heat loss does."""
    truth = flat(heater=12000.0, setpoint=K0 + 20.0)
    data = month(truth, noisy=True, weather=winter_weather(mean_c=11.0, seed=2))
    res = calibrate(
        flat(heater=12000.0, setpoint=K0 + 20.0),
        data,
        guess={**WRONG, "heating.thermostat.power": 8000.0},
    )
    heater = res.finding("heating.thermostat.power")
    assert heater.verdict == NOT_ENOUGH_DATA
    assert "never ran at full power" in heater.reason
    storage = res.finding("zone.air.capacity")
    assert storage.verdict == NOT_ENOUGH_DATA and "night" in storage.reason
    loss = res.finding("zone.envelope.conductance")
    assert loss.verdict == GOOD
    assert abs(res.values["zone.envelope.conductance"] / 180.0 - 1) < 0.05
    assert res.verdict == NOT_ENOUGH_DATA
    assert res.headline.startswith("Not enough data for")


def test_gas_heating_leaves_only_the_base_load():
    truth = flat(machine="gas")
    res = calibrate(flat(machine="gas"), month(truth, noisy=True), guess=wrong_for(truth))
    base = res.finding("base.power")
    assert base.verdict == GOOD and abs(base.value / 150.0 - 1) < 0.05
    for key in (
        "zone.envelope.conductance",
        "zone.air.capacity",
        "heating.thermostat.power",
    ):
        f = res.finding(key)
        assert f.verdict == NOT_ENOUGH_DATA and not f.measured  # no number shown
        assert "gas" in f.reason and f.sentence.endswith("not measured")
    assert set(res.values) == {"base.power"}  # nothing else was fitted
    assert "runs on gas" in res.headline


def test_a_twin_missing_a_big_load_is_not_calibrated():
    """An electric car charging 2.3 kW from 01:00 to 05:00 that the twin does
    not know about: the month's total can be absorbed, the hours cannot."""
    car = Appliance(
        schedule=Schedule([2300.0 if 1 <= h < 5 else 0.0 for h in range(24)]), name="car"
    )
    truth = flat(extra_gains=[car])
    res = calibrate(flat(), month(truth, noisy=True), guess=WRONG)
    assert res.hourly_error > 0.30
    assert res.verdict == NOT_ENOUGH_DATA
    assert "does not yet reproduce your hourly electricity" in res.headline
    assert "smart plug" in res.headline


@pytest.mark.skipif(not engine_available(), reason="a 2R2C fit takes minutes on NumPy")
def test_two_node_home_with_the_start_state_in_the_uncertainty():
    """Walls take a week or two to forget the month before, so the unknown start
    counts in the uncertainty; the truth must still be inside it."""

    def two():
        return build_home(
            ThermalZone(
                160.0,
                1.5e7,
                ventilation=40.0,
                fabric_capacity=1.2e8,
                fabric_coupling=600.0,
                temperature=K0 + 19,
                fabric_temperature=K0 + 18,
            ),
            gains=[
                BaseLoad(150.0),
                Appliance(schedule=KITCHEN, name="kitchen"),
                Appliance(schedule=LIVING, name="living"),
            ],
            conditioning=[
                HeatPump(
                    5000.0,
                    cop=3.0,
                    setpoint=None,
                    setpoint_schedule=SETBACK,
                    name="heating",
                )
            ],
            backend="rust",
        )

    truth = {
        "zone.envelope.conductance": 160.0,
        "zone.air.capacity": 1.5e7,
        "zone.fabric.capacity": 1.2e8,
        "heating.thermostat.power": 5000.0,
        "base.power": 150.0,
    }
    guess = {
        k: v * f
        for (k, v), f in zip(truth.items(), (1.5, 0.6, 0.5, 1.4, 0.55), strict=True)
    }
    res = calibrate(two(), month(two(), noisy=True), guess=guess)
    for name, e in errors(res, truth).items():
        assert abs(e) <= 1.5 * res.uncertainty[name] + 0.02, (
            name,
            e,
            res.uncertainty[name],
        )
    assert res.finding("zone.fabric.capacity").unit == "MJ per °C"
    assert abs(res.values["zone.envelope.conductance"] / 160.0 - 1) < 0.05


@pytest.mark.skipif(not engine_available(), reason="eight fits; minutes on NumPy")
def test_the_reported_uncertainty_covers_the_truth_across_noise():
    """Over eight independent noisy months the truth falls inside the reported
    ± for at least 85 % of (parameter, month) pairs: the ± means what it says."""
    hits = total = 0
    for seed in range(8):
        res = calibrate(flat(), month(flat(), noisy=True, seed=200 + seed), guess=WRONG)
        for name, e in errors(res).items():
            hits += abs(e) <= res.uncertainty[name]
            total += 1
    assert hits / total >= 0.85, f"{hits}/{total}"


