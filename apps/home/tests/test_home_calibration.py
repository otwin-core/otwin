def test_from_ingest_series_aligns_meter_and_weather():
    """A Datadis-shaped hourly series and an Open-Meteo-shaped one, the weather
    with a 2-hour gap (interpolated) — the same record as built by hand."""
    n = 31 * 24
    t0 = int(START.timestamp())
    hours = t0 + 3600 * np.arange(n)
    kwh = 0.3 + 0.2 * np.sin(np.arange(n) / 7.0)
    temp = 8.0 + 4.0 * np.sin(np.arange(n) / 11.0)
    elec = ingest.Series(
        "electricity_import", "ES00", ingest.INTERVAL, hours, hours + 3600, kwh * 3.6e6
    )
    keep = np.ones(n, dtype=bool)
    keep[40:42] = False
    out = ingest.Series(
        "outdoor_temperature",
        "40,-3",
        ingest.INSTANT,
        hours[keep],
        hours[keep],
        temp[keep] + K0,
    )
    data = HourlyData.from_series(elec, out)
    np.testing.assert_allclose(data.electricity_kwh, kwh, rtol=1e-12)
    np.testing.assert_allclose(data.outdoor_c[keep], temp[keep], atol=1e-9)
    assert np.all(np.isfinite(data.outdoor_c))  # the gap was filled
    keep[40:47] = False  # a 7-hour gap is too long to invent
    out = ingest.Series(
        "outdoor_temperature",
        "40,-3",
        ingest.INSTANT,
        hours[keep],
        hours[keep],
        temp[keep] + K0,
    )
    with pytest.raises(NotEnoughData, match="outdoor temperature is missing"):
        HourlyData.from_series(elec, out)


