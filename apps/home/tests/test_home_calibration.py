K0 = ZERO_CELSIUS
FIT_BACKEND = "rust" if engine_available() else "numpy"
START = datetime(2026, 1, 1, tzinfo=timezone.utc)
SETBACK = Schedule([K0 + (20.0 if 7 <= h < 23 else 16.0) for h in range(24)])
TRUTH = {
    "zone.envelope.conductance": 180.0,
    "zone.air.capacity": 1.2e7,
    "heating.thermostat.power": 4500.0,
    "base.power": 150.0,
}
#: Where every fit starts: 50 % off, in both directions.
WRONG = {
    "zone.envelope.conductance": 270.0,
    "zone.air.capacity": 0.6e7,
    "heating.thermostat.power": 6750.0,
    "base.power": 75.0,
}
NOISE = {"noise_relative": 0.05, "noise_kwh": 0.08}


def flat(
    *,
    heater: float = 4500.0,
    setpoint: float | None = None,
    machine: str = "heat_pump",
    extra_gains=(),
    backend: str = FIT_BACKEND,
):
    """A 1R1C flat, heat pump (COP 3) with a night setback unless ``setpoint``."""
    if machine == "heat_pump":
        heating = HeatPump(
            heater,
            cop=3.0,
            setpoint=setpoint,
            setpoint_schedule=None if setpoint else SETBACK,
            name="heating",
        )
    else:
        heating = Boiler(24e3, setpoint=None, setpoint_schedule=SETBACK, name="heating")
    return build_home(
        ThermalZone(180.0, 1.2e7, ventilation=30.0, temperature=K0 + 19.0),
        gains=[
            BaseLoad(150.0),
            Appliance(schedule=KITCHEN, name="kitchen"),
            Appliance(schedule=LIVING, name="living"),
            *extra_gains,
        ],
        conditioning=[heating],
        backend=backend,
    )


def month(truth, *, noisy: bool, seed: int = 7, weather=None, **kw) -> HourlyData:
    return synthetic_month(
        truth,
        start=START,
        outdoor_c=weather or winter_weather(seed=1),
        seed=seed,
        **(NOISE if noisy else {}),
        **kw,
    )


def wrong_for(twin) -> dict[str, float]:
    return {k: v for k, v in WRONG.items() if k in twin.model.param_names}


def errors(result, truth=TRUTH) -> dict[str, float]:
    return {k: result.values[k] / v - 1.0 for k, v in truth.items() if k in result.values}


