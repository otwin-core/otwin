/* The text for key in lang, {name} filled from values. */
export function translate(lang, key, values) {
  const table = TEXTS[lang] || TEXTS.en;
  let text = key in table ? table[key] : TEXTS.en[key];
  if (text === undefined) return key;
  if (typeof text !== "string") return text;
  for (const [k, v] of Object.entries(values || {})) text = text.split(`{${k}}`).join(String(v));
  return text;
}

/* A number as lang writes it (Spanish: 2958, 12.958,5). */
export function number(lang, x, digits = 0) {
  return Number(x).toLocaleString(lang === "es" ? "es-ES" : "en-GB", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}

export const LangContext = createContext("en");

/* t(key, values) and n(number, digits) in the current language. */
export function useT() {
  const lang = useContext(LangContext);
  return useMemo(
    () => ({
      lang,
      t: (key, values) => translate(lang, key, values),
      n: (x, digits) => number(lang, x, digits),
    }),
    [lang],
  );
}
